"""Docs must not quote test counts or the number of views by hand.

The README once said 201 tests and "two views" while 301 tests ran and there were three views. Counts live in docs/status.md, generated by
tools/project_status.py (CI runs it with --check). These tests keep the prose honest: no hand-typed counts in the documents people read first,
and the README names every view the app has.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# Documents that must not carry hard-coded counts. Dated records (assessment-response, validate-review-replan, grading log, superpowers plans)
# are deliberately excluded: they say "recorded on <date>".
CHECKED = ["README.md", "docs/evidence-summary.md", "docs/frontend.md", "docs/pitch/deck-outline.md", "docs/team-handoff.md",
           "docs/ml-developer-prompt.md", "docs/ml-model.md", "docs/decision-support.md", "docs/pilot-readiness.md", "docs/pitch/video-script.md",
           "docs/pitch/submission-checklist.md", "docs/judge-qa.md"]

COUNT = re.compile(r"(?<![\d,.])\d{2,4}(?:-| )(?:[A-Za-z]+(?:-[A-Za-z]+)? ){0,4}(?:tests|checks|check)\b")
ALLOWED = (
    "2,000",                 # plausible weightings in the rank-steadiness run
    "30 plots", "30 sites",  # a field sample size, not a test count
)


def test_no_hand_typed_test_counts():
    offenders = []
    for name in CHECKED:
        text = (ROOT / name).read_text(encoding="utf-8")
        for n, line in enumerate(text.splitlines(), 1):
            for m in COUNT.finditer(line):
                if any(a in m.group(0) for a in ALLOWED):
                    continue
                offenders.append(f"{name}:{n}: {m.group(0)!r}")
    assert not offenders, "hard-coded counts (link docs/status.md instead):\n" + "\n".join(offenders)


def test_status_file_exists_and_is_linked_from_the_readme():
    assert (ROOT / "docs" / "status.md").exists()
    assert "docs/status.md" in (ROOT / "README.md").read_text(encoding="utf-8")


def test_the_readme_names_every_view_and_says_seven():
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    html = (ROOT / "frontend" / "index.html").read_text(encoding="utf-8")
    assert len(set(re.findall(r'data-view="([a-z]+)"', html))) == 7
    for view in ("Home", "Map", "Sites", "Trends", "Tracker", "Methods and limits", "Advanced tools"):
        assert f"**{view}**" in readme
    assert "seven pages" in readme
    assert "three views" not in readme and "two views" not in readme

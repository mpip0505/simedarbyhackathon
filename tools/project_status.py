"""The one place the project's test counts and view count live.

    python tools/project_status.py            # recount and rewrite docs/status.md
    python tools/project_status.py --check    # exit 1 if docs/status.md is out of date (used by CI)
    python tools/project_status.py --stdout   # print the counts, write nothing

Hard-coded counts in prose go stale with every commit (the README once said 201 tests while 301 ran). Docs therefore link to docs/status.md instead of
quoting numbers. The counts are measured, not typed:
  - Python tests: `pytest --collect-only` over backend/tests and ml/tests
  - frontend unit tests: the summary line of `node --test frontend/tests/*.test.mjs`
  - browser checks: the number of `await check(` calls in frontend/tools/smoke.mjs (the browser test itself needs a running API and Chrome)
  - views: the number of `data-view=` navigation buttons in frontend/index.html
The date and commit are NOT part of the comparison, so `--check` only fails when a count or the view list changes.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATUS = ROOT / "docs" / "status.md"


def run(cmd: list[str]) -> str:
    out = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return out.stdout + out.stderr


def python_tests() -> int:
    text = run([sys.executable, "-m", "pytest", "backend/tests", "ml/tests", "--collect-only", "-q"])
    m = re.search(r"(\d+) tests? collected", text)
    if not m:
        raise SystemExit("could not count Python tests:\n" + text[-400:])
    return int(m.group(1))


def frontend_tests() -> int:
    import glob
    files = sorted(glob.glob(str(ROOT / "frontend" / "tests" / "*.test.mjs")))
    text = run(["node", "--test", *files])
    m = re.search(r"^# tests (\d+)", text, re.M)
    if not m:
        raise SystemExit("could not count frontend tests:\n" + text[-400:])
    return int(m.group(1))


def browser_checks() -> int:
    return len(re.findall(r"await check\(", (ROOT / "frontend" / "tools" / "smoke.mjs").read_text(encoding="utf-8")))


VIEW_NAMES = {"prioritise": "Plant first", "report": "Before and after", "pilot": "Pilot plan"}


def views() -> list[str]:
    html = (ROOT / "frontend" / "index.html").read_text(encoding="utf-8")
    keys = re.findall(r'data-view="([a-z]+)"', html)
    return [VIEW_NAMES.get(k, k) for k in dict.fromkeys(keys)]


def commit() -> str:
    return run(["git", "rev-parse", "--short", "HEAD"]).strip() or "unknown"


def body(counts: dict) -> str:
    return (
        "# Project status (generated)\n\n"
        "Generated by `python tools/project_status.py`; do not edit by hand. CI runs `python tools/project_status.py --check`, so these numbers cannot drift from the code.\n"
        "Other documents link here instead of quoting counts.\n\n"
        "| Measure | Count | How it is counted |\n|---|---|---|\n"
        f"| Python tests | {counts['python']} | `pytest --collect-only` over `backend/tests` and `ml/tests` |\n"
        f"| Frontend unit tests | {counts['frontend']} | summary of `node --test frontend/tests/*.test.mjs` |\n"
        f"| Browser checks | {counts['browser']} | `await check(` calls in `frontend/tools/smoke.mjs` (needs a running API and Chrome to execute) |\n"
        f"| Views | {len(counts['views'])} ({', '.join(counts['views'])}) | `data-view=` buttons in `frontend/index.html` |\n\n"
        "These are counts of tests that exist, not a statement that they pass on your machine; run the commands in the README to see that.\n"
    )


def collect() -> dict:
    return {"python": python_tests(), "frontend": frontend_tests(), "browser": browser_checks(), "views": views()}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if docs/status.md is out of date")
    ap.add_argument("--stdout", action="store_true", help="print the counts and write nothing")
    args = ap.parse_args()
    counts = collect()
    text = body(counts)
    if args.stdout:
        print(text)
        return
    if args.check:
        current = STATUS.read_text(encoding="utf-8") if STATUS.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/status.md is out of date. Run: python tools/project_status.py\n\nmeasured now:\n" + text)
            raise SystemExit(1)
        print("docs/status.md is current:", {k: v for k, v in counts.items()})
        return
    STATUS.write_text(text, encoding="utf-8")
    print(f"wrote {STATUS} (commit {commit()}): {counts}")


if __name__ == "__main__":
    main()
